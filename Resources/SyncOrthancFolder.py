#!/usr/bin/python3

# Taken from https://hg.orthanc-server.com/orthanc-authorization/

#
# This maintenance script updates the content of the "Orthanc" folder
# from the Orthanc release "ORTHANC_RELEASE", so that each run gives the
# same files. Change "ORTHANC_RELEASE" to move to another release.
#

import multiprocessing
import os
import stat
import urllib.request

TARGET = os.path.join(os.path.dirname(__file__), 'Orthanc')
PLUGIN_SDK_VERSION = '1.13.0'
REPOSITORY = 'https://orthanc.uclouvain.be/hg/orthanc/raw-file'

# The tag of the Orthanc release that every file comes from
ORTHANC_RELEASE = 'Orthanc-%s' % PLUGIN_SDK_VERSION

# "DownloadOrthancFramework.cmake" of a release does not know the MD5 of its
# own source archive (Orthanc adds it to mainline afterwards)
FRAMEWORK_MD5 = {
    '1.13.0' : 'cc95d3e509612b541e10e91c831fbfe3',
}

FILES = [
    ('OrthancFramework/Resources/CMake/AutoGeneratedCode.cmake', 'CMake'),
    ('OrthancFramework/Resources/CMake/Compiler.cmake', 'CMake'),
    ('OrthancFramework/Resources/CMake/DownloadOrthancFramework.cmake', 'CMake'),
    ('OrthancFramework/Resources/CMake/DownloadPackage.cmake', 'CMake'),
    ('OrthancFramework/Resources/CMake/GoogleTestConfiguration.cmake', 'CMake'),
    ('OrthancFramework/Resources/CMake/EmbedResources.py', 'CMake'),
    ('OrthancFramework/Resources/Toolchains/LinuxStandardBaseToolchain.cmake', 'Toolchains'),
    ('OrthancFramework/Resources/Toolchains/MinGW-W64-Toolchain32.cmake', 'Toolchains'),
    ('OrthancFramework/Resources/Toolchains/MinGW-W64-Toolchain64.cmake', 'Toolchains'),
    ('OrthancFramework/Resources/Toolchains/MinGWToolchain.cmake', 'Toolchains'),
    ('OrthancServer/Plugins/Samples/Common/ExportedSymbolsPlugins.list', 'Plugins'),
    ('OrthancServer/Plugins/Samples/Common/OrthancPluginCppWrapper.cpp', 'Plugins'),
    ('OrthancServer/Plugins/Samples/Common/OrthancPluginCppWrapper.h', 'Plugins'),
    ('OrthancServer/Plugins/Samples/Common/OrthancPluginException.h', 'Plugins'),
    ('OrthancServer/Plugins/Samples/Common/OrthancPluginsExports.cmake', 'Plugins'),
    ('OrthancServer/Plugins/Samples/Common/VersionScriptPlugins.map', 'Plugins'),
]

SDK = [
    'orthanc/OrthancCPlugin.h',
]


def Download(x):
    branch = x[0]
    source = x[1]
    target = os.path.join(TARGET, x[2])
    print(target)

    try:
        os.makedirs(os.path.dirname(target))
    except:
        pass

    url = '%s/%s/%s' % (REPOSITORY, branch, source)

    with open(target, 'wb') as f:
        try:
            f.write(urllib.request.urlopen(url).read())
        except:
            print('ERROR %s' % url)
            raise


commands = []

for f in FILES:
    commands.append([ ORTHANC_RELEASE,
                      f[0],
                      os.path.join(f[1], os.path.basename(f[0])) ])

for f in SDK:
    commands.append([
        'Orthanc-%s' % PLUGIN_SDK_VERSION,
        'OrthancServer/Plugins/Include/%s' % f,
        'Sdk-%s/%s' % (PLUGIN_SDK_VERSION, f)
    ])


pool = multiprocessing.Pool(10)  # simultaneous downloads
pool.map(Download, commands)


# Add the MD5 of the source archive of each release that is not known yet
path = os.path.join(TARGET, 'CMake', 'DownloadOrthancFramework.cmake')
with open(path, 'r') as f:
    cmake = f.read()

# The official releases come first, each with its "set(...MD5...)" line, and end
# with a blank line before the development snapshots: a new release goes there
SNAPSHOTS = '\n      # Below this point are development snapshots'

for version, md5 in sorted(FRAMEWORK_MD5.items()):
    line = '      elseif (ORTHANC_FRAMEWORK_VERSION STREQUAL "%s")\n' % version
    if line not in cmake:
        if SNAPSHOTS not in cmake:
            raise Exception('Cannot add the MD5 of Orthanc %s to %s' % (version, path))
        j = cmake.index(SNAPSHOTS)
        cmake = (cmake[:j] + line +
                 '        set(ORTHANC_FRAMEWORK_MD5 "%s")\n' % md5 + cmake[j:])

with open(path, 'w') as f:
    f.write(cmake)
